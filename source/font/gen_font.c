void get_font_assembly_line(Tsys *sys, FONT_SETTINGS *dst) {
    if (!sys || !dst) return;
    dst->radius = 3.96429f;
    dst->small_radius_mul = 1.03571f;
    dst->medium_radius_mul = 2.255f;
    dst->width_mul[0] = 1.0f;
    dst->width_mul[GLYPH_WIDTH_THIN] = 0.471429f;
    dst->width_mul[GLYPH_WIDTH_MEDIUM] = 0.842857f;
    dst->width_mul[GLYPH_WIDTH_THICK] = 1.65714f;
    for (int i = 4; i < 16; i++) dst->width_mul[i] = 1.0f;
    sys->memset(dst->width_flags, 0, sizeof(dst->width_flags));
    sys->memset(dst->move_desc_x, 0, sizeof(dst->move_desc_x));
    sys->memset(dst->move_desc_y, 0, sizeof(dst->move_desc_y));
    sys->memset(dst->move_grid_x, 0, sizeof(dst->move_grid_x));
    sys->memset(dst->move_grid_y, 0, sizeof(dst->move_grid_y));
    dst->half_width_settings_range_start = 0.607143f;
    dst->half_width_settings_range_end = 1.89286f;
    dst->descend = 0.0f;
    dst->optical_size = 0.0f;
    dst->glyph_count = GEN_GLYPH_COUNT;
    dst->glyph_grid_size[0] = GLYPH_W;
    dst->glyph_grid_size[1] = GLYPH_H;
    dst->glyph_box_hsize[0] = 6.0f;
    dst->glyph_box_hsize[1] = 10.0f;
    dst->glyph_box_center[0] = 7.0f;
    dst->glyph_box_center[1] = 11.0f;
    dst->glyph_box_default_hw = 2.0f;
    int total_segs = (int)(sizeof(s_all_segs) / sizeof(s_all_segs[0]));
    dst->glyph_segment_data = (GlyphSegment *)sys->malloc((size_t)total_segs * sizeof(GlyphSegment));
    dst->glyphs = (GLYPH_DATA *)sys->malloc((size_t)GEN_GLYPH_COUNT * sizeof(GLYPH_DATA));
    if (!dst->glyphs || !dst->glyph_segment_data) return;
    sys->memcpy(dst->glyph_segment_data, s_all_segs, (size_t)total_segs * sizeof(GlyphSegment));
    for (int i = 0; i < GEN_GLYPH_COUNT; i++) {
        GLYPH_DATA *gd = &dst->glyphs[i];
        int start = s_glyph_info[i].start;
        int count = s_glyph_info[i].count;
        gd->count = count;
        gd->segs = &dst->glyph_segment_data[start];
    }
}


