// Emits a standalone song.c rendering the recorded matrix: the compressed
// sequence and player (CompressSequence.cpp), one C function per sound used, and
// glue (constants, song_render_audio_batch()).
//
// The accumulator is fx16 (+-1.0 == +-65536). Fix bodies return fx16 directly;
// f64/f32 bodies convert via song_fx16_from_f64/_f32. PCM is fx16 * 32767 >> 16,
// clamped.
//
// An entry's two halves map independently, so every event is resolved twice,
// once per map, as live playback does. A visual case binds a sample only if its
// body calls smp(): song_voices[] is shared with the audio pass, and a stray bind
// would reseek its QOA stream mid-note.

