// Sound name -> C identifier (leading digit -> '_', non-alnum -> '_'); "" -> "s".
std::string CIdent(const std::string& in) {
  std::string out;
  for (char c : in) {
    unsigned char u = (unsigned char)c;
    out += (isalnum(u) || c == '_') ? c : '_';
  }
  if (out.empty()) out = "s";
  if (isdigit((unsigned char)out[0])) out.insert(out.begin(), '_');
  return out;
}

long FxConst(double v, int fracBits) { return (long)std::llround(v * (double)(1LL << fracBits)); }

const char* CTypeName(CodeSynthType t) {
  switch (t) {
    case kCodeSynthFix: return "int";
    case kCodeSynthF32: return "float";
    case kCodeSynthF64: default: return "double";
  }
}

// Which of the 8 wrap args a body references; `pan` makes it stereo.
struct SoundArgUsage {
  bool used[kCodeSynthWrapParamCount] = {};
};

// Compiles `body` and appends its C function as `ident`, keeping only referenced
// params. Falls back to a silent stub with the error as a comment. `constPan`
// folds `pan` to 0.
void EmitSoundFunction(const std::string& ident, const std::string& body, CodeSynthType type,
                       const std::string& preludeBody, const cCodeSynthGlobals& globals,
                       RenderCtx* screen,
                       const char* globalsCPrefix, EmitCDedup& dedup,
                       std::string& out, SoundArgUsage& usage, VMType& retType,
                       bool constPan) {
  const char* cType = CTypeName(type);
  usage = SoundArgUsage{};

  auto emitStub = [&](const char* stage, const std::string& why) {
    out += "// '" + ident + "' failed to " + stage + " for export (" + why + "); emitting a silent stub.\n";
    out += std::string(cType) + " " + ident + "(void) { return 0; }\n\n";
    usage = SoundArgUsage{};
    // Already converted, so BuildFx16CallExpr adds nothing.
    retType = VMType{};
    retType.kind = (type == kCodeSynthFix) ? VMT_I32 : (type == kCodeSynthF32 ? VMT_F32 : VMT_F64);
    retType.len  = (type == kCodeSynthFix) ? 16 : 0;
  };

  VM* vm = nullptr;
  Parser* parser = nullptr;
  ParseResult* res = nullptr;
  std::string err;
  Func* fn = CodeSynthCompileForExport(body, CodeSynthExportWrapParamForType(type, constPan),
                                       preludeBody.c_str(), &globals, screen, &vm, &parser, &res, err,
                                       constPan);
  if (!fn) {
    emitStub("compile", err);
    return;
  }

  for (int i = 0; i < kCodeSynthWrapParamCount; i++) usage.used[i] = func_param_used(fn, i) != 0;
  retType = func_return_type(fn);

  // The only thing telling the two domains' instances apart in the emitted code.
  vm_set_globals_c_prefix(vm, globalsCPrefix);

  // Every body carries its own copy of the common helpers; content-hashed names
  // collapse them, so `dedup` must be shared by every call for one output.
  char* code = func_emit_c_named_dedup(fn, ident.c_str(), /*strip_unused=*/1, &dedup);
  if (code) { out += code; out += "\n"; vm->run.sys->free(code); }
  else      emitStub("emit C", vm_last_error(vm) ? vm_last_error(vm) : "out of memory");

  CodeSynthReleaseExport(vm, parser, res);
}

// `callExpr` as an fx16 sample. Fix lands by shift/cast; float results go
// through the song_fx16_from_* helpers.
std::string BuildFx16CallExpr(const std::string& callExpr, CodeSynthType type, VMType rt) {
  if (type == kCodeSynthFix) {
    if (rt.kind == VMT_I32) {
      int shift = rt.len;  // fixed-point shift, 0 if plain int
      if (shift == 16) return callExpr;
      if (shift < 16)  return "((int)(((long long)(" + callExpr + ")) << " + std::to_string(16 - shift) + "))";
      return "((int)(((long long)(" + callExpr + ")) >> " + std::to_string(shift - 16) + "))";
    }
    return (rt.kind == VMT_F32 ? "song_fx16_from_f32(" : "song_fx16_from_f64(") + callExpr + ")";
  }

  const char* cType = CTypeName(type);
  std::string asFloat;
  if (rt.kind == VMT_I32) {
    int shift = rt.len; // 0 == plain int
    asFloat = shift > 0
      ? "((" + std::string(cType) + ")(" + callExpr + ") / (" + cType + ")(1LL << " + std::to_string(shift) + "))"
      : "(" + std::string(cType) + ")(" + callExpr + ")";
  } else if ((type == kCodeSynthF32 && rt.kind == VMT_F32) || (type == kCodeSynthF64 && rt.kind == VMT_F64)) {
    asFloat = callExpr; // already the target representation
  } else {
    // An F64 body under f32, or vice versa.
    asFloat = "(" + std::string(cType) + ")(" + callExpr + ")";
  }
  return (type == kCodeSynthF32 ? "song_fx16_from_f32(" : "song_fx16_from_f64(") + asFloat + ")";
}

// %g prints whole numbers bare, and "1f" is not a C token: add ".0".
std::string FmtG(double v, int prec) {
  char buf[64];
  snprintf(buf, sizeof(buf), "%.*g", prec, v);
  std::string s = buf;
  if (s.find_first_not_of("+-0123456789") == std::string::npos) s += ".0";
  return s;
}

std::string FmtConst(double v, CodeSynthType type) {
  char buf[64];
  switch (type) {
    case kCodeSynthFix: snprintf(buf, sizeof(buf), "%ldL", FxConst(v, kCodeSynthFxShift)); break;
    case kCodeSynthF32: return FmtG(v, 9) + "f";
    case kCodeSynthF64: default: return FmtG(v, 17);
  }
  return buf;
}

// synthIdx < 0: this map has nothing for the note.
struct ResolvedVoice {
  int           synthIdx = -1;
  std::string   ident;                  // C identifier base for the sound's name
  CodeSynthType type = kCodeSynthF64;
  double        freqMul = 1.0;          // 2^((note+transpose-69)/12), relative to A4
  int           rootNote = 0;           // the sound's own defining note (for RATE)
};

const CodeSynthEntry* FindEntry(const std::vector<CodeSynthEntry>& entries, const std::string& name) {
  for (const CodeSynthEntry& e : entries)
    if (e.name == name) return &e;
  return nullptr;
}

ResolvedVoice ResolveVoice(const cCodeSynthReadonly& ro, const std::vector<CodeSynthEntry>& entries,
                           int channel, int note) {
  ResolvedVoice v;
  int ch0 = channel & 0x0f;
  int idx1 = (note >= 0 && note < 128) ? ro.map[ch0 * 128 + note] : 0;
  v.synthIdx = idx1 - 1;
  if (v.synthIdx < 0) return v;

  const std::string& name = ro.synthName[v.synthIdx];
  // Pitched against A4, not the root note, as handleMidi does.
  v.freqMul  = CodeSynthSemitoneRatio(note + ro.synthTranspose[v.synthIdx] - 69);
  v.rootNote = ro.synthRootNote[v.synthIdx];
  v.ident    = CIdent(name);
  if (const CodeSynthEntry* e = FindEntry(entries, name)) v.type = e->type;
  return v;
}

// event id == row + kEventIdBase
struct EventInfo {
  int  eventId;
  int  note;             // row's MIDI note (names the HZ/XRATE/NN/RATE constants)
  bool hasVel;           // velocity < full -> apply VELMUL
  long velFx;            // fx16 of velocity / 127 (velocity mixing is always fx16)
  ResolvedVoice audio;   // through the sound map
  ResolvedVoice visual;  // through the visual map (may be a DIFFERENT entry)
};

// A rate-dependent constant over SONG_SAMPLE_RATE, so re-#defining the rate
// retimes and repitches. Fix goes via the 64-bit SONG_FX22_PER_SAMPLE.
std::string PerSampleExpr(double perSecond, CodeSynthType type) {
  char b[96];
  switch (type) {
    case kCodeSynthFix: {
      long long num_fx22 = (long long)std::llround(perSecond * (double)(1LL << kCodeSynthFxShift));
      snprintf(b, sizeof(b), "SONG_FX22_PER_SAMPLE(%lldLL)", num_fx22);
      break;
    }
    case kCodeSynthF32:
      return "(" + FmtG(perSecond, 9) + "f / (float)SONG_SAMPLE_RATE)";
    case kCodeSynthF64: default:
      return "(" + FmtG(perSecond, 17) + " / (double)SONG_SAMPLE_RATE)";
  }
  return b;
}

std::string ConstName(const std::string& ident, int note, const char* suffix) {
  return ident + "_" + std::to_string(note) + "_" + suffix;
}

// t/phase/beat arguments. Fix multiplies in 64 bits, since beat counts the whole song.
std::string ScaledExpr(const std::string& countExpr, const std::string& perSample, CodeSynthType type) {
  switch (type) {
    case kCodeSynthFix: return "((int)((long long)" + countExpr + " * (long long)" + perSample + "))";
    case kCodeSynthF32:  return "((float)" + countExpr + " * " + perSample + ")";
    case kCodeSynthF64: default: return "((double)" + countExpr + " * " + perSample + ")";
  }
}

// Steps off SONG_SAMPLES_PER_SONGTICK so beat can't disagree with the grid. Fix
// keeps 20 extra fractional bits, or rounding would drift audibly over a song.
std::string BeatScaledExpr(const std::string& countExpr, CodeSynthType type) {
  switch (type) {
    case kCodeSynthFix:
      return "((int)(((long long)" + countExpr + " * SONG_BEAT_FX42_PER_SAMPLE) >> 20))";
    case kCodeSynthF32:
      return "((float)" + countExpr + " / (4.0f * (float)SONG_SAMPLES_PER_SONGTICK))";
    case kCodeSynthF64: default:
      return "((double)" + countExpr + " / (4.0 * (double)SONG_SAMPLES_PER_SONGTICK))";
  }
}

// Per-row process order for CompressEventMatrix, resolved through the audio map
// (which claims every entry). Must be computed identically for song.c and
// song.h, or their channel counts differ.
std::vector<int> BuildRowOrders(const SongExportInput& in) {
  const int numRows = (int)in.seq.rows.size();
  std::vector<int> orders(numRows, 0);
  if (numRows == 0 || in.entries.empty()) return orders;

  // No orders: the unconstrained path is identical.
  bool any = false;
  for (const CodeSynthEntry& e : in.entries) if (e.order != 0) { any = true; break; }
  if (!any) return orders;

  std::string spec = CodeSynthSerializeEntries(in.entries);
  cCodeSynthReadonly ro;
  char dbg[256] = {0};
  CodeSynthParse(spec.c_str(), in.workingDir.c_str(), &ro,
                 (int)sizeof(dbg), dbg, in.screen, /*forVisual=*/false);

  for (int r = 0; r < numRows; r++) {
    const SongEventRow& row = in.seq.rows[r];
    const int ch0  = row.channel & 0x0f;
    const int idx1 = (row.note >= 0 && row.note < 128) ? ro.map[ch0 * 128 + row.note] : 0;
    if (idx1 > 0) orders[r] = ro.synthOrder[idx1 - 1];
  }
  return orders;
}
